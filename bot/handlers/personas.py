def get_persona(key: str | None) -> Persona | None:
    """Возвращает Persona по ключу (case-insensitive)."""
    if not key:
        return None
    return PERSONAS.get(key.strip().lower())


def apply_persona(base_prompt: str, persona_key: str | None) -> str:
    """Префиксует `base_prompt` инструкциями выбранной персоны."""
    p = get_persona(persona_key)
    if p is None:
        return base_prompt
    return f"{p.prompt}\n\n---\n\n{base_prompt}"


def list_personas_html() -> str:
    """HTML-список всех персон для /persona без аргумента."""
    lines = ["<b>Стили общения</b>", ""]
    for p in PERSONAS.values():
        lines.append(f"  {p.emoji} <code>{p.key}</code> — {p.name}")
    lines.extend(
        [
            "",
            "Использование:",
            "  <code>/persona &lt;ключ&gt;</code> — выбрать стиль",
            "  <code>/persona off</code> — обычный ChatGPT (без стиля)",
            "  <code>/persona</code> — показать список и текущий стиль",
        ]
    )
    return "\n".join(lines)
